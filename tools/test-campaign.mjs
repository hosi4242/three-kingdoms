import assert from "node:assert/strict";
import { GENERAL_DATA } from "../browser-test/js/generals.js";
import { CAMPAIGN_STAGE_COUNT, defaultCampaignState, normalizeCampaignState, getCampaignStage, applyCampaignVictory, buildCampaignEnemyTeam } from "../browser-test/js/campaign.js";
import { migrateState } from "../browser-test/js/db.js";
