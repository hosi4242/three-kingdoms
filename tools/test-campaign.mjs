let r=applyCampaignVictory(state,1);assert.equal(r.ok,true);assert.equal(r.firstClear,true);assert.equal(state.campaign.unlockedStage,2);assert.ok(state.campaign.clearedStages.includes(1));
const goldAfterFirst=state.lord.gold, materialsAfterFirst=state.inventory.equipmentMaterials;
